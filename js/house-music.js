/* ============================================================
   🎵 เพลงพื้นหลังธีมฟาร์มของโหมด "บ้านของหนู" (เฟส 14 · 2026-08-16)

   ทำไมต้องมี: โหมดบ้าน**ไม่มีเพลงของตัวเองเลย** ใช้ `MUSIC_TRACKS` ชุดเดียวกับหน้าหลักทั้งดุ้น
   ⇒ เด็กเดินอยู่ในเมืองฟาร์มแต่ได้ยินเพลงหน้าทำโจทย์

   สเปกที่ผู้ใช้อนุมัติ (ข้อ 48 ของ QUEST-DESIGN.md):
     ① เล่น **เฉพาะตอนอยู่ในเมือง** — ออกจากโหมดบ้านแล้วกลับไปใช้ชุดเดิมของหน้าหลัก
     ② **3 ชั้น: ทำนอง + เบส + คอร์ด**
     ③ **4 เพลง เพลงละ ~60-75 วินาที**
     ④ **วนเรียงไปเรื่อยๆ ไม่เปลี่ยนตามฉาก/เวลา/เควสต์**

   🔒 กติกาที่ล็อก (ห้ามย้อนโดยไม่ถามผู้ใช้):
     - **ทุกชั้นเป็น `sine` ล้วน ห้าม sawtooth/square** (= นิยามของ "แข็งกระด้าง" ที่ผู้ใช้สั่งให้เลี่ยง)
     - **ห้ามใส่กลอง/เพอร์คัสชัน**
     - **อยู่ในคีย์ C major / F major / A minor เท่านั้น** — เพราะ `playCorrect` (C-E-G) และ
       `playClick` (E5+E6) ดังทับเพลงตลอดเวลาในโหมดบ้าน คีย์อื่นจะกัดกัน
     - ทำนองอยู่ช่วง **C4-C6** · ห้ามโน้ตสูงค้างยาว
     - **master ยังเป็น 0.025 ห้ามดังขึ้น** — คุมความดังรายชั้นที่ `MUSIC_LAYER_MIX` ใน shared/audio.js
     - ใช้ปุ่มเพลงเดิม (`p1quiz_music`) ไม่มี setting แยก

   ⚠ **ไม่มีตัวเลขความดังอยู่ในไฟล์นี้เลย** — ไฟล์นี้เก็บแต่ "โน้ต" ส่วนการผสมเสียงอยู่ที่
     `js/shared/audio.js` ที่เดียว (แก้ความดังชั้นไหนก็ไปแก้ที่นั่น)

   โหลดแบบ lazy พร้อมชุดบ้านจาก js/games-ar.js — เปิดออกมาที่ `window.HouseMusic`
   ============================================================ */
(function(){
  'use strict';

  /* ความถี่โน้ต (equal temperament, A4 = 440) — เขียนเป็นชื่อโน้ตเพื่อให้อ่าน/แก้ทำนองได้จริง */
  const N = {
    C3:130.81, D3:146.83, E3:164.81, F3:174.61, G3:196.00, A3:220.00, As3:233.08, B3:246.94,
    C4:261.63, D4:293.66, E4:329.63, F4:349.23, G4:392.00, A4:440.00, As4:466.16, B4:493.88,
    C5:523.25, D5:587.33, E5:659.25, F5:698.46, G5:783.99, A5:880.00, B5:987.77,
    C6:1046.50, _:null,
  };
  /* แปลง "โน้ต:จังหวะ" เป็นรูปที่ scheduler ใช้ — คอร์ดเขียนคั่นด้วย + เช่น "C4+E4+G4:4" */
  function seq(str){
    return str.trim().split(/\s+/).map(tok=>{
      const p = tok.split(':');
      const beats = parseFloat(p[1]);
      const names = p[0].split('+');
      const f = names.map(n2 => N[n2]);
      return [names.length > 1 ? f : f[0], beats];
    });
  }

  /* ============================================================
     เพลงที่ 1 — "เช้าที่ฟาร์ม" · C major · 92 bpm
     คอร์ด C - G - Am - F (วน 16 จังหวะ) · ทำนอง 104 จังหวะ ≈ 68 วินาที
     ============================================================ */
  const T1 = {
    name:'เช้าที่ฟาร์ม', bpm:92, layers:{
      lead: seq(`
        C5:1 E5:1 G5:1 E5:1   F5:1 E5:1 D5:2   C5:1 D5:1 E5:1 F5:1   G5:2 _:2
        G5:1 A5:1 G5:1 E5:1   F5:1 D5:1 C5:2   E5:1 G5:1 A5:1 G5:1   E5:2 _:2
        C5:.5 D5:.5 E5:1 G5:1 E5:1   D5:1 C5:1 D5:2   E5:1 F5:1 G5:1 A5:1   G5:3 _:1
        A5:1 G5:1 F5:1 E5:1   D5:1 E5:1 F5:2   E5:1 D5:1 C5:1 D5:1   C5:3 _:1
        C5:1 E5:1 G5:1 E5:1   F5:1 E5:1 D5:2   E5:1 G5:1 A5:1 G5:1   E5:2 _:2
        F5:1 E5:1 D5:1 C5:1   D5:2 E5:2   G5:1 E5:1 D5:1 C5:1   C5:3 _:1
      `),
      bass: seq(`C3:4 G3:4 A3:4 F3:4`),
      chord:seq(`C4+E4+G4:4 B3+D4+G4:4 A3+C4+E4:4 A3+C4+F4:4`),
    }};

  /* ============================================================
     เพลงที่ 2 — "เดินเล่นในทุ่ง" · F major · 84 bpm
     คอร์ด F - C - Dm - C · ช้ากว่าเพลงแรก ให้รู้สึกเดินทอดน่อง
     ============================================================ */
  const T2 = {
    name:'เดินเล่นในทุ่ง', bpm:84, layers:{
      lead: seq(`
        F5:1 A5:1 G5:1 F5:1   E5:2 D5:2   C5:1 D5:1 E5:1 F5:1   G5:2 _:2
        A5:1 G5:1 F5:1 E5:1   F5:2 A5:2   G5:1 F5:1 E5:1 D5:1   C5:3 _:1
        C5:1 F5:1 A5:1 F5:1   G5:1 E5:1 C5:2   D5:1 E5:1 F5:1 G5:1   F5:2 _:2
        A5:1 G5:1 A5:1 F5:1   E5:1 F5:1 G5:2   F5:1 E5:1 D5:1 C5:1   F5:3 _:1
        C5:.5 D5:.5 E5:1 F5:2   A5:1 G5:1 F5:2   E5:1 D5:1 C5:1 D5:1   E5:2 _:2
        F5:1 G5:1 A5:1 C6:1   A5:2 G5:2   F5:1 E5:1 D5:1 C5:1   F5:3 _:1
      `),
      bass: seq(`F3:4 C3:4 D3:4 C3:4`),
      chord:seq(`F3+A3+C4:4 C4+E4+G4:4 D4+F4+A4:4 C4+E4+G4:4`),
    }};

  /* ============================================================
     เพลงที่ 3 — "สายลมกับต้นไม้" · A minor · 76 bpm
     คอร์ด Am - F - C - G · ช้าและนุ่มที่สุดในชุด (ตอนเดินเล่นเรื่อยๆ)
     ⚠ A minor ยังเป็นคีย์ที่ playCorrect (C-E-G) เข้ากันได้ เพราะใช้โน้ตชุดเดียวกับ C major
     ============================================================ */
  const T3 = {
    name:'สายลมกับต้นไม้', bpm:76, layers:{
      lead: seq(`
        A4:2 C5:2   E5:2 D5:2   C5:1 B4:1 A4:2   _:1 A4:1 C5:2
        F5:2 E5:2   D5:2 C5:2   B4:1 C5:1 D5:2   E5:3 _:1
        E5:1 D5:1 C5:1 B4:1   A4:2 C5:2   D5:1 E5:1 F5:1 E5:1   D5:3 _:1
        C5:2 E5:2   G5:2 F5:2   E5:1 D5:1 C5:2   B4:2 _:2
        A4:1 B4:1 C5:1 D5:1   E5:2 C5:2   D5:1 C5:1 B4:1 A4:1   A4:3 _:1
      `),
      bass: seq(`A3:4 F3:4 C3:4 G3:4`),
      chord:seq(`A3+C4+E4:4 F3+A3+C4:4 C4+E4+G4:4 B3+D4+G4:4`),
    }};

  /* ============================================================
     เพลงที่ 4 — "กลับบ้านตอนเย็น" · C major · 88 bpm
     คอร์ด C - Am - F - G (คอร์ดชุดที่เด็กคุ้นที่สุด) · จบชุดแล้ววนกลับเพลงที่ 1
     ============================================================ */
  const T4 = {
    name:'กลับบ้านตอนเย็น', bpm:88, layers:{
      lead: seq(`
        G4:1 C5:1 E5:2   D5:1 C5:1 B4:2   A4:1 C5:1 E5:1 D5:1   C5:2 _:2
        E5:1 G5:1 E5:1 C5:1   D5:2 F5:2   E5:1 D5:1 C5:1 B4:1   C5:3 _:1
        C5:1 D5:1 E5:1 F5:1   G5:2 E5:2   F5:1 E5:1 D5:1 C5:1   D5:3 _:1
        E5:1 F5:1 G5:1 A5:1   G5:2 E5:2   D5:1 E5:1 F5:1 D5:1   C5:2 _:2
        A4:1 C5:1 E5:1 G5:1   F5:2 D5:2   E5:1 C5:1 D5:1 B4:1   C5:3 _:1
        G4:1 A4:1 B4:1 C5:1   E5:2 G5:2   E5:1 D5:1 C5:1 G4:1   C5:4
      `),
      bass: seq(`C3:4 A3:4 F3:4 G3:4`),
      chord:seq(`C4+E4+G4:4 A3+C4+E4:4 F3+A3+C4:4 B3+D4+G4:4`),
    }};

  const TRACKS = [T1, T2, T3, T4];

  /* ความยาวจริงของเพลง (วินาที) — คิดจากชั้นทำนองซึ่งเป็นตัวตัดสินว่าเพลงจบ
     ใช้ทั้งหน้าทดสอบเพลงและชุดเทส (สเปกกำหนดว่าต้องอยู่ราว 60-75 วิ) */
  function trackSeconds(t){
    const beats = t.layers.lead.reduce((a, s) => a + s[1], 0);
    return beats * 60 / t.bpm;
  }

  window.HouseMusic = {
    TRACKS,
    names: ()=> TRACKS.map(t => t.name),
    seconds: ()=> TRACKS.map(trackSeconds),
    /* เข้าเมือง = สลับมาใช้ชุดฟาร์ม · ออกจากเมือง = คืนชุดเดิมของหน้าหลัก
       ⚠ ทั้งคู่ต้อง idempotent — `enterHouseGame()` ถูกเรียกซ้ำได้ (ตัวจริงกันไว้ที่ setMusicPlaylist) */
    use:   ()=>{ if(typeof setMusicPlaylist === 'function') setMusicPlaylist(TRACKS); },
    release: ()=>{ if(typeof setMusicPlaylist === 'function') setMusicPlaylist(null); },
    /* หน้าทดสอบเพลงในเมนูตั้งค่า — **ปิดเพลงพื้นหลังให้เงียบก่อน แล้วค่อยเปิดเพลงที่เลือก** */
    preview: i =>{ if(typeof playMusicTrack === 'function') playMusicTrack(TRACKS, i); },
    /* เลิกฟัง = กลับไปเล่นชุดฟาร์มตามปกติตั้งแต่เพลงแรก (เด็กยังอยู่ในเมือง ต้องไม่เงียบสนิท)
       ⚠ ห้ามทำด้วยการสลับไป null แล้วสลับกลับ — จะได้ยินเพลงหน้าหลักแวบหนึ่งตรงกลาง */
    stopPreview: ()=>{ if(typeof playMusicTrack === 'function') playMusicTrack(TRACKS, 0); },
    /* ปิดเสียงสนิท (ใช้ตอนออกจากหน้าโดยที่เพลงพื้นหลังถูกปิดอยู่) */
    silence: ()=>{ if(typeof stopMusic === 'function') stopMusic(true); },
  };
})();
