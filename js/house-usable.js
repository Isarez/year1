/* ============================================================
   🪑 ของตกแต่งที่ใช้งานได้จริง (Usable Furniture) — เฟส 17 ของโหมด "บ้านของหนู"
   (ข้อ 57.2 ของ QUEST-DESIGN.md · ผู้ใช้อนุมัติแผน 2026-08-17)

   ปัญหาที่แก้: ตอนนี้เก้าอี้นั่งได้ เครื่องดนตรีเล่นได้ **ที่เหลือแตะแล้วเด้งเฉยๆ**
   ⇒ เหตุผลเดียวที่จะซื้อของคือความสวย

   🔒 กติกาที่ล็อกไว้ (ห้ามย้อนโดยไม่ถามผู้ใช้)
   - **ทุกอันต้องทำงานในโลก 3D ห้ามเปิด popup เต็มจอ** — บทเรียนจากตู้ปลาเฟส 11
     (popup ที่ไม่เหมือนของจริง ผู้ใช้สั่งถอดทั้งระบบ 2026-08-17)
   - **ห้ามมีของชิ้นไหนที่ "ใช้ได้วันละครั้ง" แล้วไม่บอกว่าทำไมกดไม่ได้**
   - **ห้ามข้ามวันของระบบเกม** — เตียงเปลี่ยนแค่ "แสงกลางวัน/กลางคืน" ของฉากเท่านั้น
     เควสต์รายวัน/ผักที่ปลูก/ความหิวสัตว์ ยังผูกกับวันจริงเหมือนเดิม
     (ไม่งั้นเด็กนอนรัวๆ = เก็บผักได้ไม่จำกัดและรีเซ็ตเควสต์ได้เอง)
   - **ห้ามแก้ `material.color` ของ mesh ตรงๆ** — วัสดุถูกแคชรวมตามสี (`toonMat`) แก้ทีเดียว
     เพี้ยนทั้งเมือง ⇒ ต้อง `clone()` ก่อนเสมอ (กติกาเดียวกับ `setupLamp`)

   📁 รูปแบบไฟล์: `HOUSE_USABLE(kit)` แบบเดียวกับ `js/house-pet-toys.js`
      ⇒ **ต้องโหลดก่อน `js/house.js`** (house.js เรียกตอนโหลดไฟล์)
   ============================================================ */
function HOUSE_USABLE(kit){
  const k = kit || {};
  const bubble = (t, say) => { if(k.charBubble) k.charBubble(t, say); };
  const toast  = (ic, m)  => { if(k.toast) k.toast(ic, m); };
  const puff   = (g, n, col, spread) => { if(k.particles) k.particles(g, n, col, spread); };

  /* ---------- 📚 นิทานสั้น 1 หน้า ----------
     ⚠ สั้นพอที่จะอ่านจบในฟองคำพูด 2 ฟอง (ฟองละ ~2.2 วิ) เด็ก 5 ขวบยังไม่อ่านคล่อง
       ⇒ ประโยคสั้น คำง่าย และ **ต้องจบในหน้าเดียวเสมอ** ไม่มี "อ่านต่อพรุ่งนี้" */
  const TALES = [
    ['🐰 กระต่ายน้อยตื่นเช้ามาก', 'มันวิ่งไปทักทายทุกคนในทุ่ง แล้วก็ได้เพื่อนใหม่ 3 ตัว!'],
    ['🐢 เต่าตัวน้อยเดินช้าที่สุดในป่า', 'แต่มันไม่เคยหยุดเดิน สุดท้ายมันก็ถึงยอดเขาก่อนใคร'],
    ['⭐ ดาวดวงเล็กกลัวว่าตัวเองไม่สว่างพอ', 'แต่คืนนั้นมีเด็กคนหนึ่งมองขึ้นฟ้าแล้วยิ้มให้มันพอดี'],
    ['🌱 เมล็ดเล็กๆ ถูกฝังไว้ในดินมืดๆ', 'มันรดน้ำทุกวัน แล้ววันหนึ่งก็โผล่ขึ้นมาเป็นดอกไม้'],
    ['🐦 ลูกนกยังบินไม่เป็น', 'มันลองกระพือปีกทุกวัน จนวันหนึ่งลมก็พามันขึ้นฟ้าจริงๆ'],
    ['🐟 ปลาน้อยหลงทางในทะเลกว้าง', 'มันถามทางปูใจดี แล้วก็ว่ายกลับถึงบ้านก่อนค่ำ'],
    ['🌙 พระจันทร์ง่วงนอนทุกเช้า', 'แต่มันรอจนพระอาทิตย์มาถึงก่อนเสมอ แล้วค่อยไปพักผ่อน'],
    ['🐘 ช้างตัวใหญ่กลัวหนูตัวจิ๋ว', 'พอได้คุยกันจริงๆ ทั้งคู่ก็กลายเป็นเพื่อนซี้กัน'],
    ['🍯 หมีน้อยแบ่งน้ำผึ้งให้เพื่อน', 'ตัวเองเหลือน้อยลง แต่กลับอิ่มใจมากกว่าเดิม'],
    ['🎈 ลูกโป่งหลุดมือลอยขึ้นฟ้า', 'มันได้เห็นเมืองทั้งเมืองจากข้างบน แล้วโบกมือลาทุกคน'],
    ['🐝 ผึ้งน้อยทำงานทั้งวัน', 'ตอนเย็นมันกลับรัง แล้วดอกไม้ทุกดอกก็โบกไหวขอบคุณ'],
    ['☔ ฝนตกทั้งวันจนออกไปเล่นไม่ได้', 'เด็กๆ เลยสร้างบ้านผ้าห่มในห้อง แล้วสนุกกว่าเดิมอีก'],
  ];
  let taleI = -1;
  function nextTale(){
    /* วนไปเรื่อยๆ ไม่สุ่มซ้ำติดกัน — เด็กแตะรัวๆ ต้องได้เรื่องใหม่ทุกครั้ง */
    taleI = (taleI + 1 + ((Math.random() * (TALES.length - 1)) | 0)) % TALES.length;
    return TALES[taleI];
  }

  /* ---------- ของแต่ละชิ้นทำอะไร ----------
     ⚠ `id` ต้องตรงกับคลังเฟอร์นิเจอร์ (js/house-furniture.js) เป๊ะ */
  const USE = {
    /* 🛏️ เตียง — ท่านอนยังเป็นของเดิม (`action:'sleep'` → startSit) ตัวนี้ทำงาน "หลังนอนลงแล้ว" */
    bed:   {kind:'sleep'},
    crib:  {kind:'sleep'},
    'bunk-bed': {kind:'sleep'},
    'canopy-bed': {kind:'sleep'},
    'day-bed': {kind:'sleep'},
    /* 📺 ทีวี */
    tv: {kind:'tv'},
    /* 🐠 ตู้ปลา */
    aquarium: {kind:'tank'},
    'aquarium-sea': {kind:'tank'},
    /* 🚿 ห้องน้ำ */
    shower:   {kind:'wash'},
    bathtub:  {kind:'wash'},
    'bath-sink': {kind:'wash'},
    sink:     {kind:'wash'},
    /* 📚 ชั้นหนังสือ (แตะแล้วอ่านเลย) · มุมอ่านหนังสือ (นั่งลงก่อนแล้วค่อยอ่าน — action ยังเป็น 'sit') */
    bookshelf: {kind:'read'},
    'reading-nook': {kind:'read', viaSit:true},
  };
  function useOf(id){ return USE[id] || null; }

  /* ============================================================
     📺 ทีวี — เปิด/ปิดจริง มีภาพขยับในจอ
     ⚠ วัสดุต้อง clone ก่อนเปลี่ยนสี (แคชรวมทั้งเมือง) · แถบภาพเป็น mesh ที่สร้างตอนเปิด/ลบตอนปิด
     ============================================================ */
  function tvScreen(g){
    let m = null;
    g.traverse(o=>{ if(o.userData && o.userData.tvScreen) m = o; });
    return m;
  }
  function tvToggle(g){
    const scr = tvScreen(g);
    if(!scr){ bubble('✨'); return false; }
    const on = !g.userData.tvOn;
    g.userData.tvOn = on;
    if(!scr.userData.tvOrig){
      scr.material = scr.material.clone();               /* ⚠ clone ก่อนแตะสีเสมอ */
      scr.userData.tvOrig = scr.material.color.clone();
    }
    if(on){
      scr.material.color.setHex(0xfff3c4);
      /* แถบภาพเลื่อนขึ้นในจอ — ใช้ระบบ anim ของตกแต่งเดิม (kind 'bob') ไม่ได้เขียนลูปใหม่ */
      if(!g.userData.tvBars && k.box){
        const bars = [];
        [[0x81d4fa, .1], [0xffab91, -.06]].forEach(([c, y], i)=>{
          const b = k.box(.92, .1, .015, c);
          b.position.set(scr.position.x, scr.position.y + y, scr.position.z + .02);
          b.userData.anim = {kind:'bob', sp:2.4, amp:.2, ph:i * 2.6};
          g.add(b); bars.push(b);
        });
        g.userData.tvBars = bars;
        if(k.recollectAnim) k.recollectAnim(g);
      }
      bubble('📺');
      toast('📺', 'เปิดทีวีแล้ว! แตะอีกครั้งเพื่อปิดนะ');
    }else{
      scr.material.color.copy(scr.userData.tvOrig);
      (g.userData.tvBars || []).forEach(b => { if(b.parent) b.parent.remove(b); });
      g.userData.tvBars = null;
      if(k.recollectAnim) k.recollectAnim(g);
      bubble('🌙');
    }
    return true;
  }

  /* ============================================================
     🐠 ตู้ปลา — โปรยอาหารแล้วปลาว่ายเร็วขึ้นชั่วครู่ (ในโมเดล 3D ไม่ใช่ popup)
     ⚠ เร่งด้วย "เวลาชดเชย" (`animShift`) ไม่ใช่คูณ `s` ตรงๆ — คูณตรงๆ เฟสจะกระโดด
       ปลาจะวาร์ปตำแหน่งตอนเริ่ม/หมดเวลาเร่ง
     ============================================================ */
  const TANK_BOOST = 8;                 /* วินาที */
  function tankFeed(g){
    g.userData.tankBoost = TANK_BOOST;
    puff(g, 10, 0xffd54f, .34);         /* เม็ดอาหารโปรยลงตู้ */
    bubble('🐠');
    toast('🐠', 'ให้อาหารปลาแล้ว! ดูสิ ปลาว่ายเร็วขึ้นเลย');
    return true;
  }

  /* ============================================================
     🚿 ฝักบัว/อ่าง — เด็กล้างหน้าล้างมือเอง (ท่า `scrub` ที่มีอยู่แล้ว + ฟองสบู่)
     ⚠ **ไม่ได้ทำเป็น "อาบน้ำให้น้องจากในบ้าน" ตามสเปกต้นฉบับ** — สัตว์เลี้ยงเดินเข้าตัวบ้านไม่ได้
       (`updatePet()` ทำงานเฉพาะ `hScene === 'out'`) ถ้าสั่งอาบในบ้านจะไม่มีตัวน้องให้เห็นเลย
       ⇒ ของชิ้นนี้เป็นกิจวัตรของเด็กเอง แล้ว **เตือนเรื่องน้องเปื้อนให้แทน** ถ้าถึงเวลาอาบ
     ============================================================ */
  function washUp(g){
    if(k.pose) k.pose('scrub', 1700);
    puff(g, 9, 0xe1f5fe, .3);
    bubble('🫧');
    /* น้องเปื้อนอยู่ = บอกทางต่อเสมอ ห้ามปล่อยให้เด็กเดาเอง */
    if(k.petDirty && k.petDirty()){
      toast('🐾', 'ล้างหน้าเรียบร้อย! เพื่อนตัวน้องก็อยากอาบน้ำเหมือนกันนะ ออกไปที่สนามหน้าบ้านแล้วแตะตัวน้องได้เลย');
    }else{
      toast('🫧', 'ล้างหน้าล้างมือให้สะอาดแล้ว สดชื่นเลย!');
    }
    return true;
  }

  /* ============================================================
     📚 ชั้นหนังสือ — อ่านนิทานสั้น 1 หน้าในโลก 3D (ฟองคำพูด 2 ฟอง ไม่ใช่ popup)
     ============================================================ */
  function readBook(g){
    const t = nextTale();
    if(k.pose) k.pose('read', 3600);
    bubble(t[0], true);
    if(k.later) k.later(()=> bubble(t[1], true), 2400);
    return true;
  }

  /* ============================================================
     🛏️ เตียง — นอนตอนกลางคืนแล้วข้ามไปเช้า
     ⚠ เปลี่ยนแค่ธีมกลางวัน/กลางคืน (`setTheme`) **ห้ามแตะวันของระบบเกม**
     ============================================================ */
  function sleepWake(){
    if(!k.isNight || !k.setNight) return false;
    if(!k.isNight()){
      bubble('💤');
      toast('☀️', 'งีบสักครู่นะ · ตอนกลางคืนมานอนที่เตียง แล้วจะข้ามไปเช้าวันใหม่ได้เลย');
      return false;
    }
    if(k.fade) k.fade(()=>{
      k.setNight(false);
      toast('🌅', 'อรุณสวัสดิ์! เช้าวันใหม่แล้ว');
    });
    else{ k.setNight(false); toast('🌅', 'อรุณสวัสดิ์! เช้าวันใหม่แล้ว'); }
    return true;
  }

  /* ---------- ท่าเด็กที่เฟสนี้เพิ่ม (house.js ถามมาจาก charPoseAt) ----------
     คืน null = ไม่รู้จักท่านี้ ให้ตกไปใช้ตารางเดิม */
  function pose(kind, pr, o){
    const AZ = (o && o.ARM_Z) || [0, 0];
    if(kind !== 'read') return null;
    /* 📖 ท่าอ่านหนังสือ: ยกมือ 2 ข้างขึ้นระดับอก (เหมือนถือเล่มเปิดอยู่) แล้วก้มหน้าลงอ่านเล็กน้อย
       ⚠ แขนห้ามยกเกิน ~2.0 rad — กล้อง iso มองลงเกือบจากบนหัว มือที่สูงกว่านั้นหลบหลังหัวหมด
       ⚠ เอน (lean) ห้ามเกิน .26 rad — `rig` หมุนรอบฝ่าเท้า เอนมากเห็นเป็นล้มคว่ำ */
    const c = pr < .12 ? pr / .12 : (pr < .9 ? 1 : 1 - (pr - .9) / .1);
    const turn = Math.sin(pr * Math.PI * 3) * .12 * c;      /* ขยับมือเหมือนพลิกหน้ากระดาษ */
    return {
      lean: c * .13, legX: 0, hop: 0,
      aL: -c * 1.15 + turn, aR: -c * 1.15 - turn,
      zL: AZ[0] - c * .3, zR: AZ[1] + c * .3,
    };
  }

  return {
    USE, TALES, useOf, pose,
    tvToggle, tankFeed, washUp, readBook, sleepWake,
    TANK_BOOST,
    /* เร่งเวลาอนิเมชันตู้ปลาที่กำลังถูกเร่งอยู่ — house.js เรียกทุกเฟรมของ decor ที่มี anim
       คืน "เวลาชดเชย" (วินาที) ที่ต้องบวกเพิ่มเข้ากับนาฬิกาอนิเมชันของกลุ่มนี้ */
    tickBoost(g, dt){
      const left = g.userData.tankBoost || 0;
      if(left <= 0) return 0;
      g.userData.tankBoost = Math.max(0, left - dt);
      /* ค่อยๆ ลดความเร็วลงตอนใกล้หมดเวลา ⇒ ไม่มีจังหวะ "หยุดกึก" */
      const k2 = Math.min(1, left / 1.5);
      return dt * 1.8 * k2;
    },
  };
}
